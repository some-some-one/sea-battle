#!/usr/bin/env python3
"""The golden and charcoal keys (the author's pictures, 2026-11-16) embedded in code: src/shared/KeyPixels.luau.

Uploaded images can stay private to their author (players see nothing, Studio shows them), so the game builds
the keys itself in an EditableImage from these pixels, as it does for the icons (tools/make_icons.py).

Input: assets/ui/key_gold.png and assets/ui/key_charcoal.png (cut from docs/trailer/goldenkey.png, the hole
made transparent). Output: each key at SIDE px, 4 bits per channel, run-length coded:
  'z' + 3 hex digits   a transparent run of 1..4096 pixels
  RGBA as 4 hex digits + 1 hex digit   that colour for 1..16 pixels
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIDE = 96


def encode(path):
    img = Image.open(path).convert("RGBA").resize((SIDE, SIDE), Image.LANCZOS)
    px = [tuple(c >> 4 for c in p) for p in img.getdata()]
    out, i, n = [], 0, len(px)
    while i < n:
        if px[i][3] == 0:
            j = i
            while j < n and px[j][3] == 0 and j - i < 4096:
                j += 1
            out.append("z%03x" % (j - i - 1))
        else:
            j = i
            while j < n and px[j] == px[i] and j - i < 16:
                j += 1
            r, g, b, a = px[i]
            out.append("%x%x%x%x%x" % (r, g, b, a, j - i - 1))
        i = j
    return "".join(out)


def main():
    keys = {name: encode(os.path.join(ROOT, "assets", "ui", f"key_{name}.png")) for name in ("gold", "charcoal")}
    lines = ["--!nonstrict",
             "-- GENERATED by tools/make_keys.py - do not edit by hand.",
             "-- The golden and charcoal keys (the author's pictures) at %d px, 4 bits a channel, run-length coded:" % SIDE,
             "-- 'z' + 3 hex digits for a transparent run, else RGBA (4 hex digits) + a run length (1 hex digit).",
             "return {", "\tside = %d," % SIDE]
    for name, data in keys.items():
        lines.append('\t%s = "%s",' % (name, data))
    lines.append("}")
    with open(os.path.join(ROOT, "src", "shared", "KeyPixels.luau"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print({k: len(v) for k, v in keys.items()})


if __name__ == "__main__":
    main()
